import com.hitech.lms.auth.model.EmailVerificationToken;
import org.springframework.data.jpa.repository.JpaRepository;
import org.springframework.data.jpa.repository.Modifying;
import org.springframework.data.jpa.repository.Query;
import org.springframework.data.repository.query.Param;
import org.springframework.stereotype.Repository;

import java.time.LocalDateTime;
import java.util.Optional;

@Repository
public interface EmailVerificationTokenRepository extends JpaRepository<EmailVerificationToken, Long> {

    Optional<EmailVerificationToken> findByToken(String token);

    // Find the most recent unused token for a user (for resend feature)
    Optional<EmailVerificationToken> findTopByUserIdAndUsedFalseOrderByCreatedAtDesc(Long userId);

    // Cleanup: delete all expired tokens (can be run by a scheduled cron job)
    @Modifying
    @Query("DELETE FROM EmailVerificationToken t WHERE t.expiresAt < :now")
    void deleteAllExpiredTokens(@Param("now") LocalDateTime now);
}