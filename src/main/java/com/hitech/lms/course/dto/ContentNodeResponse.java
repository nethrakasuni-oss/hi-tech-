import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Data;
import lombok.NoArgsConstructor;

import java.time.LocalDateTime;
import java.util.List;

/**
 * Content node response — represents one node in the Week/Module/Topic tree.
 * Includes its children recursively for the full tree.
 */
@Data @Builder @NoArgsConstructor @AllArgsConstructor
public class ContentNodeResponse {
    private Long id;
    private String nodeType;       // WEEK, MODULE, TOPIC
    private String title;
    private Long parentId;
    private Integer sortOrder;
    private LocalDateTime createdAt;
    private List<ContentNodeResponse> children;  // recursive children
    private List<MaterialResponse> materials;    // materials at this node
}
