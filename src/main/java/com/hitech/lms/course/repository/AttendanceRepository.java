import com.hitech.lms.course.model.Attendance;
import org.springframework.data.jpa.repository.JpaRepository;
import org.springframework.data.jpa.repository.Query;
import org.springframework.data.repository.query.Param;
import org.springframework.stereotype.Repository;

import java.time.LocalDate;
import java.util.List;
import java.util.Optional;

@Repository
public interface AttendanceRepository extends JpaRepository<Attendance, Long> {

    // Find a specific attendance record for upsert logic
    Optional<Attendance> findByCourseIdAndStudentIdAndDate(Long courseId, Long studentId, LocalDate date);

    // Get all attendance records for a course on a specific date
    @Query("SELECT a FROM Attendance a JOIN FETCH a.student WHERE a.course.id = :courseId AND a.date = :date ORDER BY a.student.fullName ASC")
    List<Attendance> findByCourseIdAndDate(@Param("courseId") Long courseId, @Param("date") LocalDate date);

    // Get all distinct dates for which attendance has been recorded for a course
    @Query("SELECT DISTINCT a.date FROM Attendance a WHERE a.course.id = :courseId ORDER BY a.date DESC")
    List<LocalDate> findDistinctDatesByCourseId(@Param("courseId") Long courseId);
}
