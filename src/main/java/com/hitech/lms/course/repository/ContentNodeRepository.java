import com.hitech.lms.course.model.ContentNode;
import org.springframework.data.jpa.repository.JpaRepository;
import org.springframework.data.jpa.repository.Query;
import org.springframework.data.repository.query.Param;
import org.springframework.stereotype.Repository;

import java.util.List;

@Repository
public interface ContentNodeRepository extends JpaRepository<ContentNode, Long> {

    // Get all top-level nodes (WEEK nodes) for a course, ordered by sort_order
    List<ContentNode> findByCourseIdAndParentIsNullOrderBySortOrderAsc(Long courseId);

    // Get all children of a parent node, ordered
    List<ContentNode> findByParentIdOrderBySortOrderAsc(Long parentId);

    // Get all nodes for a course (for full tree retrieval)
    @Query("SELECT n FROM ContentNode n WHERE n.course.id = :courseId ORDER BY n.sortOrder ASC")
    List<ContentNode> findAllByCourseId(@Param("courseId") Long courseId);

    // Count nodes by type for a course
    long countByCourseIdAndNodeType(Long courseId, ContentNode.NodeType nodeType);
}
