import com.hitech.lms.exam.model.AttemptAnswer;
import org.springframework.data.jpa.repository.JpaRepository;
import org.springframework.data.jpa.repository.Modifying;
import org.springframework.data.jpa.repository.Query;
import org.springframework.data.repository.query.Param;
import org.springframework.stereotype.Repository;

import java.util.List;
import java.util.Optional;

@Repository
public interface AttemptAnswerRepository extends JpaRepository<AttemptAnswer, Long> {

    List<AttemptAnswer> findByAttemptId(Long attemptId);

    Optional<AttemptAnswer> findByAttemptIdAndQuestionId(Long attemptId, Long questionId);

    // Count answered questions in an attempt
    @Query("SELECT COUNT(a) FROM AttemptAnswer a WHERE a.attempt.id = :attemptId AND a.answerText IS NOT NULL AND a.answerText <> ''")
    long countAnswered(@Param("attemptId") Long attemptId);
}
